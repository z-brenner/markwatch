#!/usr/bin/env node
// Refreshes the bundled IANA RDAP bootstrap snapshot and regenerates the
// network allowlist that becomes the CSP connect-src.
//
//   npm run update-bootstrap
//
// The allowlist is the privacy boundary of the app: every host the browser may
// contact is listed in src/data/allowlist.json, and the build writes exactly
// that list into the Content-Security-Policy. Review the diff before committing.
//
// Behind an HTTPS proxy on Node 22, run with NODE_USE_ENV_PROXY=1.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IANA = 'https://data.iana.org/rdap/';
const FILES = ['dns', 'ipv4', 'ipv6', 'asn'];

// Fixed lookup endpoints (not from the bootstrap).
const FIXED = [
  { host: 'cloudflare-dns.com', purpose: 'DNS over HTTPS (primary resolver)' },
  { host: 'dns.google', purpose: 'DNS over HTTPS (fallback resolver)' },
  { host: 'crt.sh', purpose: 'Certificate Transparency search' },
  { host: 'data.iana.org', purpose: 'IANA RDAP bootstrap (drift check)' },
];

// RDAP referral targets observed in browser testing that are not themselves
// listed in the bootstrap files. LACNIC redirects Brazilian space to NIC.br.
const REFERRALS = [{ host: 'rdap.registro.br', purpose: 'RDAP referral target (LACNIC → NIC.br)' }];

async function getJson(url) {
  const res = await fetch(url, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

const boot = {};
for (const f of FILES) boot[f] = await getJson(`${IANA}${f}.json`);

const hosts = new Map();
const add = (host, purpose) => {
  if (!hosts.has(host)) hosts.set(host, purpose);
};
for (const { host, purpose } of FIXED) add(host, purpose);

const skipped = [];
const compact = {};
for (const f of FILES) {
  compact[f] = {
    publication: boot[f].publication,
    services: boot[f].services.map(([keys, urls]) => {
      const https = urls.filter((u) => u.startsWith('https://'));
      for (const u of urls) if (!u.startsWith('https://')) skipped.push({ file: f, url: u, keys });
      for (const u of https) add(new URL(u).hostname, f === 'dns' ? 'RDAP (domain registry)' : 'RDAP (regional internet registry)');
      return [keys, https.map((u) => (u.endsWith('/') ? u : `${u}/`))];
    }),
  };
}
for (const { host, purpose } of REFERRALS) add(host, purpose);

const allowlist = {
  generatedAt: new Date().toISOString(),
  bootstrapPublication: boot.dns.publication,
  note: 'Generated by scripts/update-bootstrap.mjs. This list is the CSP connect-src. Do not edit by hand.',
  skippedNonHttps: skipped,
  hosts: [...hosts.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([host, purpose]) => ({ host, purpose })),
};

await writeFile(path.join(root, 'src/data/rdap-bootstrap.json'), JSON.stringify(compact) + '\n');
await writeFile(path.join(root, 'src/data/allowlist.json'), JSON.stringify(allowlist, null, 1) + '\n');
console.log(`bootstrap ${boot.dns.publication}: ${allowlist.hosts.length} hosts, ${skipped.length} non-https URLs skipped`);
